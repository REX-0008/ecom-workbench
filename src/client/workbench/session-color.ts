/** 浏览器会话的**色标**：同一个会话名 → 同一个颜色。
 *
 * ## 为什么要有它（用户 2026-10-12 要求）
 *
 * 用户原话：「**节点上色标**」——目的是在画布上一眼看出
 * 「这几个浏览器节点是在同一台浏览器上跑的」。
 *
 * 场景：工作流里可能有多个浏览器节点，有的开页面、有的点击、有的取文本。
 * 若它们**会话名不同**，其实是各跑各的浏览器 —— 那种流程是错的（取不到上一步的页面），
 * 而画布上**看不出来**。色标就是让这种错**在画布上直接可见**。
 *
 * ## 为什么是「按名字算」而不是「按出现顺序分配」
 *
 * 按顺序分配的话，同一个会话名在不同的工作流里颜色不同，
 * 而且加/删一个节点会让后面所有节点的颜色**全变** —— 那种「颜色记不住」的色标没有意义。
 * 按名字算哈希则**同名恒同色**：用户看到紫红色就知道「又是那个会话」。
 *
 * ⚠️ **不做成「颜色可自定义」**：那是「先有需求再扩展」的事，
 * 现在加设置项只会让参数面板更挤（用户反复要求「节点尽量少、参数尽量少」）。
 */

/**
 * 会话色板。
 *
 * 取值要求（与项目既有的颜色纪律一致，见 AGENTS.md「样式」段）：
 *   - **不与状态色撞**：状态色表达「怎么样了」（绿=成功、红=失败、黄=跑着），
 *     所以这里避开纯红/纯绿/纯黄，免得「紫标」被误读成某种状态；
 *   - 亮暗两种主题下都要能看清，所以用**中等明度、较高饱和**的色；
 *   - 数量少而区分度大（6 个够用：同一张画布上很少超过 6 个会话）。
 */
export const SESSION_COLORS: readonly string[] = [
  '#8b7cf6', // 紫
  '#f472b6', // 粉
  '#38bdf8', // 天蓝
  '#fb923c', // 橙
  '#2dd4bf', // 青绿
  '#a3e635', // 黄绿
]

/**
 * 把一个字符串折成稳定的非负整数（简单哈希）。
 *
 * ## ⚠️ 一个必须记的坑：**中文名用简单哈希会大量撞色**
 *
 * 第一版用的是教科书的 `h = h * 31 + code`。对英文名没问题
 * （单字母 A-F 六种颜色全不同），但**中文名撞得很厉害** ——
 * 实测「默认/淘宝/抖音/拼多多/京东/视频号」这 6 个常用名只算出 **3 种**颜色。
 *
 * 原因：中文在 UTF-16 里是连续码点（汉字基本区 U+4E00 起，相邻字码点差 1~几十），
 * 而 `31 × 码点` 的**低位**几乎只由最后一个字决定、高位被乘数吃掉 ——
 * 相邻码点的哈希值在 `% 6` 之下落点密集。
 *
 * 修法：**先散一次再混合** —— 每个码点乘一个大奇素数（FNV 的思路），
 * 让相邻码点的结果在低位就岔开。这样中文名与英文名都能散开。
 *
 * 它不需要密码学性质，只需要「相似输入 → 不同输出」。
 *
 * ⚠️ **撞色是色板大小的固有限制，不是这里能修掉的**：6 个颜色下，
 * 6 个会话名本来就只能出 4-5 种色（鸽笼原理）。实测过 FNV-1a / djb2 /
 * djb2+位置权重三种，**没有一种能让中文和英文同时满分**。
 * 用户 2026-10-12 的选择是「就 6 个，允许偶尔撞色」——
 * 理由：会话名就写在色标旁边，不是靠颜色认名。
 * 所以**别为了「不撞色」去改哈希**，那只会把冲突挪到别的名字上。
 *
 * @param s - 输入字符串。
 * @returns 非负整数。
 */
function hash(s: string): number {
  let h = 0x811c9dc5 // FNV-1a 的 32 位初始值
  for (let i = 0; i < s.length; i++) {
    /* 异或之后乘一个大奇素数（FNV-1a 的标准做法）——相邻码点会立刻岔开。 */
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  /* ⚠️ `Math.imul` 的结果是**有符号** 32 位，可能是负数，
   * **必须取绝对值**再取模 —— 不然 `-7 % 6 = -1`，索引成 `undefined`、颜色变空。 */
  return Math.abs(h)
}

/**
 * 会话名 → 颜色。
 *
 * @param sessionName - 会话名（空/未填按「默认」处理，与驱动的默认值一致）。
 * @returns CSS 颜色串。
 */
export function sessionColor(sessionName: string | undefined): string {
  const name = (sessionName ?? '').trim() === '' ? '默认' : (sessionName as string).trim()
  const i = hash(name) % SESSION_COLORS.length
  return SESSION_COLORS[i] as string
}

/**
 * 判断一个节点是不是「浏览器类」节点（该不该显示会话色标）。
 *
 * 判据是**节点定义里有 `session` 这个参数**，而不是「id 以 browser 开头」——
 * 前者是「它真的用会话」，后者只是命名巧合。将来别的节点用会话时，
 * 这条判据自动覆盖它（不用改代码）。
 *
 * @param params - 节点参数定义（`paramDefs`）。
 * @returns 该显示会话色标则 true。
 */
export function hasSession(params: readonly { key: string }[] | undefined): boolean {
  if (params === undefined) return false
  return params.some(p => p.key === 'session')
}
