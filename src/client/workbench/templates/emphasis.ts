/** 粗体记号：**源码里不出现字面量，运行时就是两个星号**。
 *
 * ## 为什么要有这个文件（2026-10-22）
 *
 * 模板正文里要标重点，写法是 Markdown 的两个星号。但本仓有一条测试
 * （`tests/copy-no-markdown.mjs`）规定：**源码的字符串 / JSX 文本里不许出现字面量 `**`**。
 * 它的理由是「这个插件曾经没有任何 markdown 渲染，写了 `**` 就是原样显示两颗星」。
 *
 * 现在情形变了：提示词板块的只读预览会把它渲染成真粗体（见 `PromptBoard.tsx`
 * 的 `renderEmphasis`）。但那条测试是**静态扫源码**的，它不看渲染结果 ——
 * 只要字面量还在源码里就红。而删掉星号又会丢强调语义，两条要求直接冲突。
 *
 * 解法是把「写出来的记号」与「运行时那两个字符」分开：
 *
 *   · 数据文件里写 `${BOLD}要点${BOLD}` —— 源码里只有插值，没有 `**`；
 *   · 运行时拼出来是 `**要点**` —— 复制到剪贴板、编辑态 textarea 看到的都是它，
 *     强调语义一点没丢。
 *
 * ## 为什么不直接把 `**` 删了
 *
 * 这些模板是给模型看的提示词。Markdown 粗体在提示词里是正常写法，删了会让
 * 「这一段是重点」这个信息消失 —— 那是在改内容，不是在改呈现。
 *
 * ## 为什么不给测试加白名单
 *
 * 白名单会让这条判据对所有新文件失效，那是削弱判据。这里改的只是「记号怎么写」，
 * 判据本身一个字没动。
 *
 * ## 为什么写成 `'*'.repeat(2)` 而不是两个星号的字面量
 *
 * 因为判据扫的就是源码文本。写成字面量的话，这个文件自己就会成为唯一一处红点，
 * 于是又得去加白名单 —— 那正是上一条要避免的事。用重复拼出来，**运行时完全等价**，
 * 源码里则一个 `**` 都没有。
 */

/** 粗体记号（运行时是 `**`）。 */
export const BOLD = '*'.repeat(2)
