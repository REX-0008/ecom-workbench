/** 提示词模板的数据形状（**只有形状，没有内容**）。
 *
 * ## 为什么模板要单独放一个目录
 *
 * 模板正文是一段**很长的中文文本**。写在组件文件里会把界面逻辑挤到几百行之外，
 * 想找一个模板得滚很久；而且模板会持续增加（每加一个就动一次组件，容易碰坏渲染）。
 * 所以：**一个分类一个文件**，组件只认 `index.ts` 汇总出来的那张表。
 *
 * ## 许可证
 *
 * 正文改编自 prompt-optimizer（AGPL-3.0），**只用它的提示词文本、未复制其代码**
 * （它是 Vue 3 + naive-ui，我们是 React 18，前端完全自写）。
 * 每个数据文件头都带这条注记，见同目录各文件。
 */

/** 一个提示词模板。 */
export interface PromptTemplate {
  /** 唯一标识（只在本板块内唯一）。 */
  id: string
  /** 显示名（左栏那一行）。 */
  name: string
  /** 一句话说明：这个模板适合什么场景。 */
  desc: string
  /** 分类 id（见 `index.ts` 的 `PROMPT_CATEGORIES`）。 */
  category: string
  /**
   * 模板正文。
   *
   * 里面可以出现两种占位符，都会被识别成界面上的输入框：
   *   · `{{变量名}}` —— 双花括号，主写法；
   *   · `[占位]` —— 方括号，兼容参考项目的写法。
   * 识别规则与边界见 `vars.ts`（**故意只做简单识别**，不是通用模板引擎）。
   */
  body: string
}

/** 一个分类。 */
export interface PromptCategory {
  /** 分类 id。 */
  id: string
  /** 显示名（左栏分组标题）。 */
  label: string
}
