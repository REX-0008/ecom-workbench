/** 节点定义（纯数据：不 import 任何 Node 内置模块，客户端与宿主半共用这一份）。
 *
 * ## 这是「通用 AI 生成」，不是某一个电商业务
 *
 * 与 `ecom.copy.gen` / `ecom.image.gen` 的区别：那两件是**电商专用**（文案类型有
 * 「标题 / 卖点」、出图服务有 dashscope），本节点只做一件事 ——
 * 「把一段指令交给模型，拿回一段文字」。凡是「让模型加工一下再往下走」的场合都用它，
 * 提示词优化板块的第二步就是靠它。
 *
 * 判据（`AGENTS.md` 的七问）：它碰外部世界（模型额度）且要理解自然语言，
 * 所以是专用节点；它不需要跨请求生命周期、也不需要补偿，所以**不该**做成一份工作流。
 *
 * ## 命令体与执行层（2026-10-23 后端把执行层换成 `ctx.llm` 后改过一次）
 *
 * 本节点走 `agent` 执行方。命令体默认由 `workflow/command.ts` 的通用约定拼成
 * `{ prompt }`（见那里的 `commandOf`）。这里用 `toCommand` 把**另外两项也放进去**：
 * `input`（参考资料）与 `timeoutMs`（超时）。
 *
 * 执行层三项都读（`src/dispatch/executors.ts` 的 `createAgentExecutor`），
 * 而它背后的委派函数走 dsh 配置好的模型通道（`ctx.llm.stream`，见 `src/index.ts`
 * 的 `createLlmDelegate`）—— **不带 agent 系统提示词、不给模型任何工具**：
 * 只把文字交过去、拿回文字。这正是「干净渠道」的含义。
 *
 * ## ⚠️ 「干净渠道」≠「不许有系统提示词」（2026-10-23 澄清，别弄混）
 *
 * 用户当初说「我希望工作流里面的提示词是干净的」。这句说的是**被动塞进来的那份**：
 * dsh 自己的 agent 系统提示词（那一大段讲工具怎么用、工作区规则、身份设定的文字）
 * 与随之而来的整套工具声明。那不是用户要的，是走 agent 通道的副产品。
 *
 * 本节点的「系统提示词」参数是另一件事：**用户自己主动写的、模型按它执行的那条设定**。
 * 它是用户意图的一部分，不是被塞进来的。
 *
 * 两者不冲突，判据就一条：**这段文字是用户写的，还是框架塞的？**
 *   - 用户写的 → 该有（本节点的 `system` 参数）
 *   - 框架塞的 → 不要（`ctx.llm.stream` 这条路永远不给 tools、不读 dsh 的系统提示词装配）
 *
 * 所以下一个人看到这里有 `system` 参数时，**不要**以为它违背了「干净渠道」而删掉它。
 *
 * 注册表在 `src/nodes/index.ts` 集中维护（加节点要在这里补一行，原因见那里的说明）。
 */
