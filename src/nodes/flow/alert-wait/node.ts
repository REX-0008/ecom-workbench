/** 节点定义（纯数据：不 import 任何 Node 内置模块，客户端与宿主半共用这一份）。
 *
 * ## 它是什么
 *
 * 把「通知」与「等待」合成一个节点：先发一条 Windows 通知，再按四种模式决定停不停。
 * 拆成两个节点串着用的老问题：通知发出去之后若没接等待，人收到提醒时流程已经跑完了；
 * 而中间某一环断了，数据也跟着丢。
 *
 * ## 四种模式（`mode`）
 *
 * | 值 | 干什么 | 挂不挂起 |
 * | --- | --- | --- |
 * | `none` | 只通知，不停 | 不挂起 |
 * | `duration` | 等一段时长 | 挂起，到点由宿主半自动继续 |
 * | `until` | 等到某个时刻 | 挂起，到点自动继续 |
 * | `manual` | 等人点继续 | 挂起，不自动继续；可设超时 |
 *
 * 默认 `none`：四种里只有它不改变执行时序，其余三种都会让这次运行先结束、之后再续跑。
 * 默认值选一个会挂起的模式，等于让「只想发条通知」的人莫名其妙多出一条等待记录。
 *
 * ## 与「等待」节点（`flow.wait`）的关系
 *
 * 等待的语义、现场存盘、三种恢复方式都与它一致（都走 `workflow/snapshot.ts` 的
 * `readWaitPlan`）。本节点多出来的只有前半段：发通知。第一轮**不删** `flow.wait` ——
 * 老的挂起记录（`paused/` 里那些）仍要靠它恢复。
 *
 * ## 与「通知」节点（`flow.notify`）的关系
 *
 * 发通知这一半**复用它的实现**（引擎派发时按 `flow.notify` 找函数），
 * 所以「发不发、按什么级别发」那套规则只有一份，不会在两处各写一遍。
 *
 * ## 失败策略为什么是「走失败分支」
 *
 * 用户的定案：等人超时要有失败分支接手（原话「等人失败走失败分支就行了……
 * 由失败处理流程接手」）。这一档是**唯一**能让失败出口上的下游跑起来的取值：
 * `stop` 会整条中断、`continue` 会让两个出口都活。所以默认取它。
 *
 * ⚠️ 但「发通知失败」不该走失败分支 —— 那是附带动作，不是业务失败。
 * 引擎把这一类**自己吞掉并记一行日志**，只有「等人超时」才当节点失败抛出去。
 * 两件事分开之后，一个 `onError` 才装得下两个意图。
 */
