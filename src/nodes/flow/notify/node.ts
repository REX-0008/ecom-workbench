/** 节点定义（纯数据：不 import 任何 Node 内置模块，客户端与宿主半共用这一份）。
 *
 * ## 为什么只有一个提醒节点（用户 2026-10-22 定）
 *
 * 用户原话：「预警做成一个吧，判断要不要报可以用 if，别的节点能兼容不要创造新节点。」
 * 「比如失败提醒、预警节点提醒、不提醒之类的」。
 *
 * 所以：
 *   · **只有这一个节点**，不做「预警 / 告警 / 失败提醒」若干兄弟节点；
 *   · 「要不要报」交给条件判断节点（`flow.if`）连在前面 —— 本节点不做判断；
 *   · 发不发由**提醒设置里的「预警节点最低级别」**决定（四档，见 `detail.cautions` 第 ② 条），
 *     那项设置不归本节点管，本节点只照着执行；
 *   · 定时任务失败 / 挂起恢复失败要不要提醒是**另一项独立设置**，与本节点无关。
 *
 * 判据（`AGENTS.md` 的七问）：它碰外部世界（系统通知），所以是专用节点；
 * 但它不跨请求生命周期、也不需要补偿，所以**不该**做成一份工作流。
 *
 * 注册表在 `src/nodes/index.ts` 集中维护（加节点要在这里补一行，原因见那里的说明）。
 */
