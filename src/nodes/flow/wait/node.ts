/** 节点定义（纯数据：不 import 任何 Node 内置模块，客户端与宿主半共用这一份）。
 *
 * ## 它是什么（计划 Step 12 第一步）
 *
 * 跑到这里**把整个运行现场存下来并停下**，等条件满足后再从这一处继续。
 * 参照物两家：
 *   · **n8n Wait** —— 挂起时把执行数据写库，恢复时重新载入（我们照这个）；
 *   · **Dify human_input** —— 存运行现场，提交后沿 action 边继续（那套表单引擎**本轮不做**）。
 *
 * 三种恢复方式（2026-10-22 补齐第三种）：
 *   · **等一段时长** / **等到某个时刻** —— 到时间由宿主半自动继续；
 *   · **等人点继续** —— 一直停着，直到在运行列表里点「继续」；可设超时，超时按失败结束。
 *     用户要它的原话：「登录检测到登录失败后提醒并进入等待点……比如我不是在画布打开工作流，
 *     进入等待后怎么让他继续？」登录过期这种事，等到几号都没用，必须人来处理。
 *
 * ## 与「延迟」节点的区别（最容易混的一处，别合并）
 *
 * | | 干什么 | 代价 |
 * | --- | --- | --- |
 * | **延迟** | 在**同一次运行里**睡一会儿，进程一直占着 | 不能等几小时，也不能重启 |
 * | **等待** | 把现场**存到磁盘**后**结束这次运行**，到点由宿主半恢复 | 能等几小时、能跨重启；但会多一条运行记录 |
 *
 * 所以「等 3 秒」用延迟（简单、不留记录）；「等到明早 9 点」用等待。
 *
 * ## 为什么由调度器解释执行（不在 `NODE_IMPLS` 里）
 *
 * 它要的东西只有调度器有：这次跑到哪了、每个节点输出什么、谁被判过不可达。
 * 一个普通内置函数只看得到自己的参数与上游 —— 存不出「现场」。
 */
