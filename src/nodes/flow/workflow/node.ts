/** 「跑另一份工作流」节点。
 *
 * ## 为什么有它（用户 2026-10-15 定的方案 A）
 *
 * 三个组合层的 bat 是**纯转发**（零逻辑，只 `call` 子 bat）：
 *   - `一键下载.bat`   = 抖音 → 天猫
 *   - `全部下载.bat`   = 天猫 → 抖音（顺序与上一条**相反**）
 *   - `0一键更新.bat` = 一键下载 → 清洗入库
 *
 * 按新判据（`docs/机制-什么做成节点、什么写代码、什么做成工作流.md`），
 * 「一串固定步骤 → 整体做成一份工作流」；而组合层是**工作流调用工作流**，
 * 引擎原先没有这个能力 —— 所以补这一个节点。
 *
 * ## 照的是谁
 *
 * **n8n 的 Execute Sub-workflow 节点**（`n8n-nodes-base.executeworkflow`）。
 * 官方文档：Source 四选一（Database / Local File / Parameter / URL）；
 * 唯一选项 `Wait for Sub-Workflow Completion`。
 * 我们只需要「按编号跑本机存档里的另一份」这一种 —— 所以参数只有「跑哪一份」。
 *
 * ⚠️ **2026-10-19 把「按名字」改成「按编号」**（用户：「引用用的应该是编号而不是名称」）：
 * n8n 那边存的也是 `workflowId`（名字只做显示），我们照它。理由与做法见
 * `src/workflow/ids.ts` 的文件头。
 *
 * ⚠️ **2026-10-17 补了第二个参数「传给它的输入」**（用户 m02875：「补。」）：
 * 执行层早就会读 `params.inputs`（`run.ts` 的 `runSubWorkflow` → `readGivenInputs`），
 * 但**界面上从来没有这个控件** —— 只能手改存档，于是「组合层把参数透下去」
 * 这件事用户在界面上做不到（同一个坑：参数定义了却没人渲染）。
 *
 * ⚠️ **Dify 画布上没有子工作流节点**（它走 workflow-as-tool，要先「发布成工具」）。
 * 我们选了 n8n 那条路：直接按名字调，不必先登记。
 *
 * ## 为什么 `executor` 写 builtin 却不在 `NODE_IMPLS` 里
 *
 * 与 `flow.loop` 同一个理由（见 `src/nodes/impls.ts` 的文件头）：
 * 它**不是「派发一个节点」那类东西**，而是由调度器解释执行
 * （`src/workflow/run.ts` 的 `runSubWorkflow`）—— 它要的是「再跑一遍调度器」这种能力，
 * 派发器那层拿不到。放进 `NODE_IMPLS` 反而会被当成普通 builtin 去派发。
 *
 * ⚠️ 这是个**纯数据**模块：不许 import 任何 Node 内置模块（`tests/nodes-layout.mjs` 会查），
 * 客户端与宿主半共用这一份。
 */
