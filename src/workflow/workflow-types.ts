/** 工作流类型：**基础清单**与筛选用的纯逻辑（客户端与宿主半共用这一份）。
 *
 * ## 用户定案（m00888 + m00901）
 *
 * 用户 m00861 原话：「后期的工作流需要有类型……同时给一个设置，可独立启用。
 * 这个可独立启用不像可被他人调用是自动测出不可自选，而是人为定义的，
 * 这样几十个工作流才能分清谁是什么。」
 *
 * 用户 m00888 定：**可自由填 + 有基础清单 + 可多选**；**列表要能按类型筛**。
 *
 * ⚠️ **用户 m00901 的修正（很关键，别搞混）**：
 * 「可被调用不是设置项，而是**开始节点是什么决定的**」。
 * 所以：
 *   · **能不能启动 / 能不能被别的流程调** → 看 `flow.start` 节点的 `type` 参数；
 *   · **这份清单** → 只是给人看的标签，用于显示与筛选，**不参与任何执行判断**。
 *
 * 两者会打架，所以判据只留一处：**执行看开始节点**。
 *
 * ## 为什么基础清单放在代码里（而不在数据里）
 *
 * 收藏板块的分类是**纯数据**（用户手写的分类值存在 `collect/store.ts` 的数据里，
 * 见那里的说明）。这一份不同：它是**第一版的建议清单**，用户原话
 * 「具体怎么设计执行的时候先做一版」—— 也就是**先给一份能用的，之后再调**。
 * 放在这里意味着「改一次要发版」，但换来的是「它只有一处、不会与用户数据混在一起」。
 */

/**
 * 基础清单（第一版）。
 *
 * ⚠️ **用户可自由填，这份只是下拉里的建议** —— 不在表里的值照样存、照样显示。
 * 所以增删这里不影响任何已有存档。
 */
export const WORKFLOW_TYPE_PRESETS: readonly string[] = [
  '只可被调用',
  '可独立执行',
  '采集',
  '处理·入库',
  '组合',
]

/**
 * 一份工作流当前的类型（读存档，容错）。
 *
 * @param doc - 存档内容（不可信）。
 * @returns 类型数组（去空、去非字符串；没有则空数组）。
 */
export function readTypes(doc: unknown): string[] {
  const raw = (doc as { types?: unknown } | null | undefined)?.types
  if (!Array.isArray(raw)) return []
  return raw
    .filter((x): x is string => typeof x === 'string')
    .map(x => x.trim())
    .filter(x => x !== '')
}

/**
 * 把「基础清单」与「本机所有工作流用过的类型」合成候选。
 *
 * 与收藏分类的候选同一个做法（固定项在前、其余按字母序）——
 * 用户「输入就是新建」，所以他打过的值下次要能在下拉里看到。
 *
 * @param used - 本机所有工作流里出现过的类型。
 * @returns 候选清单（已去重）。
 */
export function typeOptions(used: readonly string[]): string[] {
  const extra = [...new Set(used)].filter(t => !WORKFLOW_TYPE_PRESETS.includes(t)).sort()
  return [...WORKFLOW_TYPE_PRESETS, ...extra]
}
